const Tiles = ({ items }) => <div className="tiles">{items.map(t => <div key={t[0]}><div className="l">{t[0]}</div><div className="v">{t[1]}</div><div className="l" style={{ color: t[3] ? '#079455' : '#7a7672' }}>{t[2]}</div></div>)}</div>;

export function ReportDoc({ kind = 'daily', title, c: cIn }) {
  const app = useApp(); const c = cIn || app.ctx; const { tools, db, demo } = c;
  const k = tools.get_kpis({ days: 1 }).kpis;
  const p = tools.get_production({ days: 1 });
  const h = tools.get_asset_health({});
  const top = k.slice(0, 4).map(x => [x.name, `${fmtNum(x.value)} ${x.unit}`, `${x.improvement_pct >= 0 ? '▲' : '▼'} ${Math.abs(x.improvement_pct)} % vs baseline`, x.improvement_pct >= 0]);
  if (kind === 'energy') {
    const e = tools.get_energy({ days: 30 });
    return <Paper c={c} title={title || 'Energy and utilities summary'}>
      <Tiles items={[['Energy, 30 days', `${fmtNum(e.energy_kwh / 1000, 0)} MWh`, ''], ['Peak demand', `${fmtNum(e.peak_kva)} kVA`, `contract ${fmtNum(e.contract_kva)}`], ...k.filter(x => x.group === 'energy').slice(0, 2).map(x => [x.name, `${fmtNum(x.value)} ${x.unit}`, `${x.improvement_pct} % vs baseline`, x.improvement_pct >= 0])]} />
      <h2>Consumption by area</h2><table><thead><tr><th>Area</th><th>MWh</th><th>Share</th></tr></thead><tbody>{e.by_area.map(a => <tr key={a.area}><td>{a.area}</td><td>{fmtNum(a.kwh / 1000, 0)}</td><td>{a.share_pct} %</td></tr>)}</tbody></table>
      <h2>Findings</h2><ul>{demo.events.filter(x => x.agent === 'Energy Agent' || /fuel|oil|air|energy/i.test(x.title || '')).filter(x => x.title).map(x => <li key={x.id}><b>{x.title}.</b> {x.diagnosis?.reco}</li>)}</ul>
    </Paper>;
  }
  if (kind === 'assets') return <Paper c={c} title={title || 'Asset health report'}>
    <Tiles items={[['Assets monitored', h.length, ''], ['In alarm', h.filter(x => x.health < 50).length, ''], ['On watch', h.filter(x => x.health >= 50 && x.health < 75).length, ''], ...k.filter(x => x.group === 'maintenance').slice(0, 1).map(x => [x.name, `${fmtNum(x.value)} ${x.unit}`, `${x.improvement_pct} % vs baseline`, x.improvement_pct >= 0])]} />
    <h2>Assets needing action</h2><table><thead><tr><th>Asset</th><th>Health</th><th>Life left</th><th>Finding</th></tr></thead><tbody>{h.filter(x => x.health < 75).map(x => <tr key={x.id}><td>{x.id} · {x.name}</td><td>{x.health}</td><td>{x.rulDays} d</td><td>{x.finding}</td></tr>)}</tbody></table>
    <h2>Recommendations</h2><ul>{demo.events.filter(e => e.diagnosis).map(e => <li key={e.id}><b>{e.asset}:</b> {e.diagnosis.reco}</li>)}</ul>
  </Paper>;
  return <Paper c={c} title={title || 'Daily performance report'}>
    <Tiles items={top} />
    <h2>Summary</h2><p>Output was {fmtNum(p.actual)} {p.unit} against a plan of {fmtNum(p.plan)} ({p.attainment_pct} %). {h.filter(x => x.health < 50).length} assets are in alarm: {h.filter(x => x.health < 50).map(x => x.id).join(', ') || 'none'}.</p>
    <h2>KPIs against baseline</h2><table><thead><tr><th>KPI</th><th>Today</th><th>Baseline</th><th>Target</th><th>Status</th></tr></thead><tbody>{k.map(x => <tr key={x.id}><td>{x.name}</td><td>{fmtNum(x.value)} {x.unit}</td><td>{fmtNum(x.baseline)}</td><td>{fmtNum(x.target)}</td><td>{x.status}</td></tr>)}</tbody></table>
    <h2>Agent findings</h2><ul>{demo.events.filter(e => e.title).map(e => <li key={e.id}><b>{e.title}.</b> {e.diagnosis?.reco}</li>)}</ul>
    <h2>Approvals waiting</h2><ul>{demo.approvals.map(a => <li key={a.id}>{a.title} ({a.from})</li>)}</ul>
  </Paper>;
}

export function WorkbookView({ sheets }) {
  const [s, setS] = useState(0); const [cell, setCell] = useState({ ref: 'A1', v: sheets[0].cols[0] });
  const sh = sheets[Math.min(s, sheets.length - 1)];
  const L = sh.cols.map((_, i) => String.fromCharCode(65 + i));
  return (
    <div className="xl">
      <div className="xl-bar"><span className="mono" style={{ width: 70 }}>{cell.ref}</span><span style={{ color: '#888', fontStyle: 'italic' }}>fx</span><span className="mono" style={{ border: 0 }}>{cell.v}</span></div>
      <div className="xl-grid"><table><thead><tr><th />{L.map(l => <th key={l}>{l}</th>)}</tr></thead><tbody>
        <tr><th>1</th>{sh.cols.map((c, i) => <td key={i} className={`h ${cell.ref === L[i] + 1 ? 'on' : ''}`} onClick={() => setCell({ ref: L[i] + 1, v: c })}>{c}</td>)}</tr>
        {sh.rows.map((r, ri) => <tr key={ri}><th>{ri + 2}</th>{r.map((c, ci) => { const v = c && typeof c === 'object' ? c.v : c; const ref = L[ci] + (ri + 2);
          return <td key={ci} className={`${typeof v === 'number' ? 'n' : ''} ${cell.ref === ref ? 'on' : ''}`} onClick={() => setCell({ ref, v: c && typeof c === 'object' ? c.f(ri + 2) : v })}>{typeof v === 'number' ? v.toLocaleString('en-IN') : v}</td>; })}</tr>)}
      </tbody></table></div>
      <div className="xl-tabs">{sheets.map((x, i) => <button key={x.name} className={i === s ? 'on' : ''} onClick={() => setS(i)}>{x.name}</button>)}</div>
    </div>
  );
}

export function DeckView({ c: cIn, name }) {
  const app = useApp(); const c = cIn || app.ctx; const { tools, db, demo } = c;
  const [i, setI] = useState(0);
  const k = tools.get_kpis({ days: 30 }).kpis;
  const k0 = demo.kpis.find(x => x.id === demo.overview[0]);
  const tr = tools.get_kpi_trend({ id: k0.id, days: 182 });
  const slides = [
    { t: 'title', h: name, s: `${demo.company} · ${demo.site} · ${fmtDate(db.anchor)}` },
    { h: `${k.filter(x => x.improvement_pct > 0).length} of ${k.length} KPIs better than baseline`, tiles: k.slice(0, 4) },
    { h: `${k0.name}: ${tr.points.at(-1).v} ${k0.unit} against a baseline of ${k0.base}`, chart: tr },
    { h: 'Where losses remain', bullets: demo.events.filter(e => e.title).map(e => e.title) },
    { h: 'Decisions needed', bullets: demo.approvals.map(a => a.title) },
  ];
  const sl = slides[i];
  return (
    <div className="grid" style={{ gridTemplateColumns: '150px minmax(0,1fr)' }}>
      <div className="thumbs">{slides.map((x, j) => <button key={j} className={j === i ? 'on' : ''} onClick={() => setI(j)}>{j + 1}. {x.h}</button>)}</div>
      <div>
        <div className={`slide ${sl.t === 'title' ? 'title' : ''}`}>
          {sl.t === 'title' ? <><div className="bars" /><div className="h1">{sl.h}</div><div style={{ color: '#cfcac3', marginTop: 8 }}>{sl.s}</div></> : <>
            <div className="sh">{sl.h}</div>
            {sl.tiles && <div className="grid g4">{sl.tiles.map(x => <div key={x.id} style={{ borderTop: '3px solid #d04a02', background: '#f6f5f3', padding: 10 }}><div style={{ fontSize: 11, color: '#7a7672' }}>{x.name}</div><div style={{ fontSize: 22 }}>{fmtNum(x.value)} <span style={{ fontSize: 12 }}>{x.unit}</span></div><div style={{ fontSize: 11, color: x.improvement_pct >= 0 ? '#079455' : '#c92a1f' }}>{x.improvement_pct} % vs baseline</div></div>)}</div>}
            {sl.chart && <Trend data={sl.chart.points.map(p => ({ t: new Date(p.t).getTime(), v: p.v }))} series={[{ key: 'v', name: k0.name }]} days={180} height={200} refs={[{ y: k0.base, label: 'Baseline', color: '#98a2b3' }, { y: k0.target, label: 'Target', color: '#079455' }]} xRefs={[{ x: db.goLive, label: 'Go-live' }]} />}
            {sl.bullets && <ul style={{ fontSize: 'clamp(12px,1.3vw,16px)', lineHeight: 1.7 }}>{sl.bullets.map(b => <li key={b}>{b}</li>)}</ul>}
          </>}
          <div className="sf"><span style={{ fontFamily: 'var(--serif)', fontWeight: 700 }}>pwc</span><span>{demo.company} · Connected Plant Intelligence</span><span>{i + 1}</span></div>
        </div>
        <div className="row" style={{ justifyContent: 'space-between', marginTop: 10 }}><button className="btn sm" onClick={() => setI(Math.max(0, i - 1))}>‹ Previous</button><span className="muted">Slide {i + 1} of {slides.length}</span><button className="btn sm" onClick={() => setI(Math.min(slides.length - 1, i + 1))}>Next ›</button></div>
      </div>
    </div>
  );
}

export function DocView({ c: cIn, name }) {
  const app = useApp(); const c = cIn || app.ctx; const { tools, demo, db } = c;
  const k = tools.get_kpis({ days: 30 }).kpis;
  const total = demo.kpis.reduce((a, x) => a + (x.lakh || 0), 0);
  return <Paper c={c} title={name} doc>
    <h2>Purpose</h2><p>This note records the value realised by the Faclon AI programme at {demo.site}, measured against the baseline locked before go-live ({fmtDate(db.baselineFrom)} – {fmtDate(db.baselineTo)}).</p>
    <h2>Value realised · ₹{(total / 100).toFixed(2)} Cr per year</h2>
    <table><thead><tr><th>KPI</th><th>Baseline</th><th>Now</th><th>Change</th><th>₹ lakh/yr</th></tr></thead><tbody>{k.map(x => <tr key={x.id}><td>{x.name}</td><td>{fmtNum(x.baseline)} {x.unit}</td><td>{fmtNum(x.value)}</td><td>{x.improvement_pct} %</td><td>{x.value_inr_lakh_yr || '—'}</td></tr>)}</tbody></table>
    <h2>Method</h2><ul><li>Each KPI uses the same definition before and after go-live.</li><li>Value is counted once, at the KPI that carries it.</li><li>Volumes are normalised to the baseline product mix.</li></ul>
  </Paper>;
}
